def get_template(template_key: str) -> str:
    """根据模板键读取管家话术。"""

    if template_key not in MESSAGE_TEMPLATES:
        raise KeyError(f"template key not found: {template_key}")
    return MESSAGE_TEMPLATES[template_key]
